"""Ultralytics validation and report exports, independent of the GUI."""
import os

# Also support importing this module without starting the main application.
if os.name == "nt":
    os.environ["MKL_THREADING_LAYER"] = "SEQUENTIAL"
os.environ["MPLBACKEND"] = "Agg"

import csv
import logging
import torch
from dataclasses import dataclass
from ultralytics import YOLO

logger = logging.getLogger("ADaCITra")


@dataclass(frozen=True)
class UltralyticsEvaluator:
    """Snapshot of the selected model, dataset and report destination."""

    model_path: str | None
    yaml_path: str | None
    output_dir: str | None
    app_version: str = "0.4.3"

    def evaluate(self):
        """Evaluate the YAML test split independently of GUI prediction data."""
        import json
        import ultralytics
        from pathlib import Path
        import yaml

        if self.model_path is None:
            raise ValueError("Please load a YOLO model first.")
        if not self.yaml_path or not os.path.isfile(self.yaml_path):
            raise ValueError("Please load a dataset YAML with a test split first.")
        if not self.output_dir:
            raise ValueError("Please set an output directory first.")
        with open(self.yaml_path, encoding="utf-8") as file:
            dataset = yaml.safe_load(file)
        if not isinstance(dataset, dict) or not dataset.get("test"):
            raise ValueError("Evaluation requires a dataset YAML containing test, train, val and names.")
        checkpoint = self.model_path
        if not checkpoint:
            raise ValueError("Please load a .pt model using Load Model first.")

        # A separate instance keeps validation/device changes out of live inference.
        evaluator = YOLO(checkpoint)
        captured = {}

        def capture_validation(validator):
            captured["confusion_matrix"] = validator.confusion_matrix

        evaluator.add_callback("on_val_end", capture_validation)
        device = "cuda:0" if torch.cuda.is_available() else "cpu"
        logger.info("Evaluation device: %s", device)
        arguments = dict(
            data=self.yaml_path, split="test", imgsz=640, conf=0.001,
            iou=0.70, max_det=300, agnostic_nms=False, device=device,
            batch=1, workers=0, half=False, plots=True,
            save_json=False, save_txt=False, visualize=False,
            project=os.path.abspath(os.path.join(self.output_dir, "evaluation")),
            name="evaluation", exist_ok=False, verbose=True,
        )
        metrics = evaluator.val(**arguments)
        cm = captured.get("confusion_matrix")
        if cm is None:
            raise RuntimeError("Ultralytics did not return its confusion matrix.")
        output = Path(metrics.save_dir)
        box = metrics.box
        precision, recall = float(box.mp), float(box.mr)
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        names = metrics.names
        names = dict(enumerate(names)) if isinstance(names, list) else names
        rows = [["Class ID", "Class Name", "Precision", "Recall", "F1 (from P/R)",
                 "AP@0.50", "AP@0.50:0.95"]]
        result_indices = {int(class_id): index for index, class_id in enumerate(box.ap_class_index)}
        for class_id, name in sorted(names.items()):
            index = result_indices.get(int(class_id))
            if index is None:
                # Classes absent from Ultralytics AP results are not assigned fabricated AP.
                rows.append([class_id, name, "", "", "", "", ""])
                continue
            p, r = float(box.p[index]), float(box.r[index])
            rows.append([class_id, name, p, r, 2*p*r/(p+r) if p+r else 0.0,
                         float(box.ap50[index]), float(box.ap[index])])
        rows.append(["Overall", "mAP", precision, recall, f1,
                     float(box.map50), float(box.map)])
        with (output / "ap_metrics_report.csv").open("w", newline="", encoding="utf-8") as file:
            csv.writer(file).writerows(rows)
        labels = [str(names[i]) for i in sorted(names)] + ["background"]
        with (output / "confusion_matrix.csv").open("w", newline="", encoding="utf-8") as file:
            writer = csv.writer(file)
            writer.writerow(["Predicted / True", *labels])
            for label, values in zip(labels, cm.matrix):
                writer.writerow([label, *values.tolist()])
        # PNGs, including normalized CM, are generated by Ultralytics itself.
        metadata = {
            "app_version": self.app_version, "ultralytics_version": ultralytics.__version__,
            "model": str(checkpoint), "validation_arguments": arguments,
            "precision": precision, "recall": recall, "f1_from_mean_pr": f1,
            "map50": float(box.map50), "map50_95": float(box.map),
            "notes": ["Evaluation uses the YAML test split, not the GUI image/GT folders.",
                      "F1 is the harmonic mean of reported P/R, not mean per-class F1.",
                      "P/R use the Ultralytics operating point; CM uses its own standard matching.",
                      "Confusion matrix rows=predicted, columns=true; last index=background.",
                      "Blank class metrics mean the class is absent from Ultralytics AP results."]
        }
        (output / "evaluation_metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
        logger.info("Ultralytics evaluation saved to %s", output)
        return metrics

